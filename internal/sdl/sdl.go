// Package sdl renders the canonical schema file: the one GraphQL SDL document that is the
// published contract of the API.
//
// It renders the schema the server actually serves — the *ast.Schema gqlgen built from
// graph/*.graphqls — rather than concatenating the source files. That way the file cannot
// describe a server that does not exist, and the test next to it only has to compare bytes.
//
// What it adds over introspection is the directive usages. Introspection declares @scope,
// @interactiveOnly and @fullReach but never says which field carries them, so a client had to
// read prose in descriptions to find out which door, scope and kind a field needs. The
// formatter prints usages, so the file says it on the field.
package sdl

import (
	"bytes"
	"regexp"

	"github.com/vektah/gqlparser/v2/ast"
	"github.com/vektah/gqlparser/v2/formatter"

	"github.com/obcode/tallox.go/graph/generated"
)

// FileName is where the canonical schema lives, relative to the repository root.
const FileName = "schema.graphql"

// header is a GraphQL comment, so every parser skips it, and it carries the Go convention for
// generated files, so linters and reviewers do too.
const header = `# Code generated by internal/sdl/cmd/sdlgen. DO NOT EDIT.
#
# The canonical contract of the Tallox GraphQL API, rendered from graph/*.graphqls by
# ` + "`go generate ./...`" + `. Unlike the schema introspection returns, it shows which fields
# carry @scope, @interactiveOnly and @fullReach.

`

// Served is the schema the handler executes.
func Served() *ast.Schema {
	// Schema() returns the parsed schema and touches no resolver, so an empty Config is enough.
	return generated.NewExecutableSchema(generated.Config{}).Schema()
}

// indentedBlank is a line holding nothing but the indentation the formatter writes for an empty
// line inside a description. It means the same as an empty line, but the pre-commit hook would
// strip it and turn the committed file into a stale one.
var indentedBlank = regexp.MustCompile(`(?m)^[ \t]+$`)

// Render prints a schema as the canonical file.
//
// Deterministic: the formatter sorts directive definitions and types by name, and fields keep
// their order from the source files, which gqlgen reads in glob (that is, name) order.
func Render(schema *ast.Schema) []byte {
	var buf bytes.Buffer
	buf.WriteString(header)
	formatter.NewFormatter(&buf, formatter.WithIndent("  ")).FormatSchema(schema)
	return indentedBlank.ReplaceAll(buf.Bytes(), nil)
}
